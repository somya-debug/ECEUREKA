// Regenerates samples/problems.json and docs/PROBLEMS.md from the problem bank in index.html.
// Usage: npm run catalog
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { loadEngine } from './load-engine.mjs';
import { ROOT } from './env.mjs';

const { PROBLEMS } = loadEngine();
const NAMES = { LED: 'LED', RES: 'Resistor', BTN: 'Button', BUZ: 'Buzzer', LDR: 'Photoresistor', POT: 'Potentiometer', RGB: 'RGB LED',
  SEG: '7-segment', PIR: 'PIR sensor', SRV: 'Servo', SR: '74HC595' };
const idx = PROBLEMS.map((p) => ({ id: p.id, title: p.title, difficulty: p.difficulty, ref: p.ref, limits: p.limits,
  tests: p.tests.length, hiddenTests: p.tests.filter((t) => t.hidden).length, hints: (p.hints || []).length }));
writeFileSync(resolve(ROOT, 'samples/problems.json'), JSON.stringify(idx, null, 2) + '\n');

let md = '# Problem catalog\n\n_Generated by `npm run catalog` from the problem bank in `index.html`. Do not edit by hand._\n\n' +
  '| # | Problem | Difficulty | Parts provided | Optimal parts | Tests (hidden) |\n|---|---|---|---|---|---|\n';
idx.forEach((p, i) => {
  const parts = Object.entries(p.limits).map(([k, v]) => `${v}× ${NAMES[k] || k}`).join(', ');
  md += `| ${i + 1} | ${p.title} (\`${p.id}\`) | ${p.difficulty} | ${parts} | ${p.ref} | ${p.tests} (${p.hiddenTests}) |\n`;
});
writeFileSync(resolve(ROOT, 'docs/PROBLEMS.md'), md);
console.log(`Wrote ${idx.length} problems to samples/problems.json and docs/PROBLEMS.md`);
